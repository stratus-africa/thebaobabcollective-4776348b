export type PageKey = keyof PageDefaults;

export function mergePageContent<K extends PageKey>(
  key: K,
  override: Record<string, unknown> | null | undefined,
): PageDefaults[K] {
  return { ...PAGE_DEFAULTS[key], ...(override ?? {}) } as PageDefaults[K];
}

